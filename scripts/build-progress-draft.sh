#!/usr/bin/env bash
# Builds supabase/functions/progress-draft/index.ts (one file, deployable from the
# Supabase dashboard): the CRM's own PA reader (src/lib/paExtractor.js, bundled)
# + supabase/functions-src/progress-draft.core.ts.
set -e
cd "$(dirname "$0")/.."
mkdir -p supabase/functions/progress-draft
npx -y esbuild@0.21.5 src/lib/paExtractor.js --bundle --format=iife --global-name=PAX --log-level=error --outfile=/tmp/pax.js
{
  echo "// @ts-nocheck"
  echo "// GENERATED by scripts/build-progress-draft.sh — edit supabase/functions-src/progress-draft.core.ts instead."
  sed -n '1,/^declare function extractFromPa/p' supabase/functions-src/progress-draft.core.ts | sed '$d'
  echo ""
  echo "// ─── The CRM's PA reader (src/lib/paExtractor.js + xlsxFormulas.js), bundled ───"
  cat /tmp/pax.js
  echo "const { extractFromPa, fetchLatestPaForSubfolder } = PAX"
  sed -n '/^declare function fetchLatestPaForSubfolder/,$p' supabase/functions-src/progress-draft.core.ts | sed '1d'
} > supabase/functions/progress-draft/index.ts
echo "built $(wc -c < supabase/functions/progress-draft/index.ts) bytes"
